package matcher // Весь код в этом файле принадлежит пакету matcher.

import (
	"fmt" // Для составления текста ошибок.

	"symbol-invert/internal/reader" // Переиспользуем чтение файла построчно из пакета reader.
)

// Template хранит "эталонный" рисунок одного символа: сам символ, его ширину
// в колонках и его 8 строк, как они выглядят в файле баннера.
type Template struct {
	Char  rune      // Сам символ, который представляет этот шаблон.
	Width int       // Сколько колонок (символов текста) занимает этот рисунок.
	Lines [8]string // 8 строк рисунка этого символа.
}

// LoadTemplates читает файл баннера (например standard.txt) и строит по одному
// шаблону для каждого печатаемого символа ASCII (коды с 32 по 126).
func LoadTemplates(bannerFile string) (map[rune]Template, error) { // Принимает имя файла баннера, возвращает готовые шаблоны.
	lines, err := reader.ReadLines(bannerFile) // Читаем сам файл баннера построчно.
	if err != nil {                            // Если файл не открылся...
		return nil, err // ...сообщаем об этом наружу.
	}

	templates := make(map[rune]Template) // Пустая карта "символ -> его шаблон" — сюда сложим результат.

	for c := rune(32); c <= rune(126); c++ { // Перебираем все печатаемые символы по порядку кода.
		index := int(c) - 32      // Порядковый номер символа в файле (пробел — нулевой).
		start := index*9 + 1      // 9 строк на символ (8 содержательных + 1 разделитель), +1 пропускает первую пустую строку файла.
		if start+8 > len(lines) { // Если для этого символа в файле не хватает строк...
			return nil, fmt.Errorf("файл баннера %s слишком короткий для символа %q", bannerFile, c) // ...файл повреждён или неполный.
		}

		var block [8]string                  // Заготовка под 8 строк текущего символа.
		copy(block[:], lines[start:start+8]) // Копируем нужный кусок из всех строк файла.

		templates[c] = Template{ // Складываем готовый шаблон в карту под ключом "сам символ".
			Char:  c,
			Width: len(block[0]), // Ширина — это длина любой из 8 строк (все 8 строк одного символа одинаковой длины).
			Lines: block,
		}
	}

	return templates, nil // Возвращаем карту со всеми 95 шаблонами.
}

// MatchRow восстанавливает исходный текст одной печатной строки: идёт слева
// направо и на каждом шаге ищет символ, чей шаблон точно совпадает со
// следующим куском строки — ровно так, как описано в задании как "core challenge".
func MatchRow(row [8]string, templates map[rune]Template) (string, error) { // Принимает одну "восьмёрку" строк и карту шаблонов.
	width := len(row[0]) // Общая ширина этой строки текста (по первой из 8 строк).

	for i := 1; i < 8; i++ {
		if len(row[i]) != width {
			return "", fmt.Errorf("строки ASCII-арта имеют разную ширину")
		}
	}

	var result []rune // Сюда будем собирать распознанные символы по одному.
	pos := 0          // Текущая позиция — с какой колонки начинаем искать очередной символ.

	for pos < width { // Пока не дошли до конца строки...
		found := false // Флаг: нашли ли подходящий символ на этом шаге.

		for c := rune(32); c <= rune(126); c++ { // Перебираем кандидатов по порядку кода — чтобы результат был предсказуемым.
			tpl, ok := templates[c] // Достаём шаблон для этого символа.
			if !ok {                // Если такого символа почему-то нет в карте...
				continue // ...пропускаем, идём к следующему.
			}

			end := pos + tpl.Width // Где закончился бы этот кандидат, если бы он тут подошёл.
			if end > width {       // Если он не помещается в оставшуюся часть строки...
				continue // ...точно не подходит, пропускаем.
			}

			match := true            // Предполагаем, что кандидат подходит, пока не доказано обратное.
			for i := 0; i < 8; i++ { // Сверяем все 8 строк блока по очереди.
				if end > len(row[i]) { // Защита: если в реальной строке почему-то меньше символов, чем ожидалось...
					match = false // ...этот кандидат не подходит.
					break
				}
				if row[i][pos:end] != tpl.Lines[i] { // Сравниваем нужный кусок строки с соответствующей строкой шаблона.
					match = false // Хоть одно несовпадение — кандидат не подходит.
					break
				}
			}

			if match { // Если все 8 строк совпали точно...
				result = append(result, c) // ...записываем этот символ в результат.
				pos = end                  // Сдвигаем позицию на ширину найденного символа.
				found = true
				break // Дальше кандидатов не перебираем — символ уже найден.
			}
		}

		if !found { // Если ни один из 95 шаблонов не подошёл точно...
			return "", fmt.Errorf("не удалось распознать символ на позиции %d", pos) // ...сообщаем, где именно распознавание сломалось.
		}
	}

	return string(result), nil // Превращаем список рун в обычную строку и возвращаем.
}
